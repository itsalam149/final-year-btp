"""
failure_modes.py
─────────────────────────────────────────────────────────────────────────────
Direct implementation for Failure Mode Analysis (Section 6.5):
1. Item-Level Flip Dynamics:
   - Negative flips (1 -> 0): items correct in FP16, broken in quantized variant (regression)
   - Positive flips (0 -> 1): items incorrect in FP16, correct in quantized variant (spurious)
   - Churn rate: total item flips / N
2. GSM8K Failure Disentanglement:
   - Format failure: no extractable numerical answer (fails #### syntax)
   - Arithmetic/logic failure: valid extracted number, but incorrect value
   - Strict vs flexible extraction gap
3. IFEval Constraint Breakdown:
   - Prompt-level strict vs loose
   - Instruction category compliance

Group ID: DTU/CSE/BTP/GP159 | DTU 2026-27
"""

import re
from typing import Dict, List, Optional, Tuple, Union
import numpy as np
import pandas as pd
from tabulate import tabulate


def analyze_flip_dynamics(
    y_fp16: np.ndarray,
    y_quant: np.ndarray,
    item_ids: Optional[List[str]] = None,
) -> Dict[str, Union[int, float, List[str]]]:
    """
    Analyzes item-level prediction churn between FP16 and a quantized variant.

    Args:
        y_fp16: 1D binary array of FP16 accuracy (1 = correct, 0 = wrong).
        y_quant: 1D binary array of quantized accuracy.
        item_ids: Optional identifiers for individual test items.

    Returns:
        Dictionary with negative_flips, positive_flips, net_change, churn_rate, regression_ids.
    """
    y_fp16 = np.asarray(y_fp16, dtype=np.int64)
    y_quant = np.asarray(y_quant, dtype=np.int64)
    n = len(y_fp16)
    if n == 0:
        return {"n": 0, "neg_flips": 0, "pos_flips": 0, "churn_rate": 0.0, "net_change": 0}

    # 1 -> 0: Regression (broken by quantization)
    neg_mask = (y_fp16 == 1) & (y_quant == 0)
    neg_flips = int(np.sum(neg_mask))

    # 0 -> 1: Spurious improvement
    pos_mask = (y_fp16 == 0) & (y_quant == 1)
    pos_flips = int(np.sum(pos_mask))

    churn_rate = float((neg_flips + pos_flips) / n)
    net_change = pos_flips - neg_flips

    regression_ids = []
    if item_ids is not None and len(item_ids) == n:
        regression_ids = [item_ids[i] for i in range(n) if neg_mask[i]]

    return {
        "n": n,
        "negative_flips": neg_flips,
        "negative_flip_rate": float(neg_flips / n),
        "positive_flips": pos_flips,
        "positive_flip_rate": float(pos_flips / n),
        "churn_rate": churn_rate,
        "net_flip_change": net_change,
        "regression_item_ids": regression_ids[:20],  # Sample first 20
    }


def analyze_gsm8k_failure_modes(
    completions: List[str],
    gold_answers: List[str],
) -> Dict[str, Union[int, float]]:
    """
    Classifies GSM8K failures into formatting errors vs arithmetic errors.

    Args:
        completions: Raw text generated by model for each problem.
        gold_answers: Ground truth numerical answers (e.g. '42').

    Returns:
        Dictionary with format_error_rate, math_error_rate, and extraction metrics.
    """
    n = len(completions)
    if n == 0:
        return {"n": 0, "format_errors": 0, "math_errors": 0}

    format_errors = 0
    math_errors = 0
    strict_correct = 0
    flexible_correct = 0

    strict_pattern = re.compile(r"####\s*(-?[\d,]+(?:\.\d+)?)")
    flexible_pattern = re.compile(r"(-?[\d,]+(?:\.\d+)?)")

    for comp, gold in zip(completions, gold_answers):
        clean_gold = str(gold).replace(",", "").strip()

        # Check strict match
        strict_match = strict_pattern.findall(comp)
        if strict_match:
            pred = strict_match[-1].replace(",", "").strip()
            if pred == clean_gold:
                strict_correct += 1
            else:
                math_errors += 1
        else:
            # Did not follow #### format
            format_errors += 1
            # Check if flexible extraction would have found it
            flex_matches = flexible_pattern.findall(comp)
            if flex_matches and flex_matches[-1].replace(",", "").strip() == clean_gold:
                flexible_correct += 1

    total_correct = strict_correct + flexible_correct

    return {
        "n_samples": n,
        "strict_correct": strict_correct,
        "strict_accuracy": float(strict_correct / n),
        "format_failures": format_errors,
        "format_failure_rate": float(format_errors / n),
        "pure_arithmetic_failures": math_errors,
        "arithmetic_failure_rate": float(math_errors / n),
        "flexible_rescued_count": flexible_correct,
        "format_filter_gap_pp": float((flexible_correct / n) * 100.0),
    }


def analyze_ifeval_categories(
    results_dict: Dict[str, float]
) -> pd.DataFrame:
    """
    Extracts instruction-level and prompt-level accuracy breakdowns from IFEval results.
    """
    rows = []
    for k, v in results_dict.items():
        if "ifeval" in k:
            rows.append({
                "metric_key": k,
                "score": v,
                "score_pct": round(v * 100.0, 2) if v <= 1.0 else v,
            })
    return pd.DataFrame(rows)

